create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role public.app_role not null default 'player',
  player_id bigint unique references public.players(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.guardian_players (
  guardian_id uuid not null references public.profiles(id) on delete cascade,
  player_id bigint not null references public.players(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (guardian_id, player_id)
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  folio text not null unique,
  player_id bigint references public.players(id) on delete set null,
  player_name text not null,
  tutor_name text,
  concept text not null,
  base_amount numeric(10,2) not null default 0 check (base_amount >= 0),
  discount_pct numeric(5,2) not null default 0 check (discount_pct between 0 and 100),
  discount_amount numeric(10,2) not null default 0 check (discount_amount >= 0),
  final_amount numeric(10,2) not null default 0 check (final_amount >= 0),
  method text not null,
  date date not null,
  status text not null default 'Pendiente',
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.calendar_events (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('partido', 'entrenamiento', 'evento')),
  title text not null,
  date date not null,
  time text not null,
  location text not null,
  result text,
  match_stats jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.injuries (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.players(id) on delete cascade,
  player text not null,
  diagnosis text not null,
  start_date date not null,
  estimated_return date,
  status text not null default 'En Tratamiento',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.attendance_logs (
  id bigint generated by default as identity primary key,
  date date not null,
  player_id bigint not null references public.players(id) on delete cascade,
  player_name text not null,
  status text not null check (status in ('Presente', 'Ausente', 'Justificado')),
  checkin_time text,
  created_at timestamptz not null default now(),
  unique (date, player_id)
);

create table if not exists public.justifications (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.players(id) on delete cascade,
  detail text,
  absence_date date not null,
  reason text not null,
  status text not null default 'Pendiente' check (status in ('Pendiente', 'Aprobada', 'Rechazada')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.justifications
  add column if not exists detail text;

create index if not exists payments_player_id_idx on public.payments (player_id);
create index if not exists calendar_events_date_idx on public.calendar_events (date);
create index if not exists injuries_player_id_idx on public.injuries (player_id);
create index if not exists attendance_logs_player_date_idx on public.attendance_logs (player_id, date desc);
create index if not exists justifications_player_id_idx on public.justifications (player_id);

-- 2. Automatización ---------------------------------------------------------

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', new.email))
  on conflict (id) do nothing;
  return new;
end;
$$;

-- Consultas seguras que las políticas RLS usan internamente.
create or replace function public.is_staff()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid())
      and role in ('admin', 'director', 'coach')
  );
$$;

create or replace function public.is_related_to_player(target_player_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    left join public.guardian_players gp on gp.guardian_id = p.id
    where p.id = (select auth.uid())
      and (p.player_id = target_player_id or gp.player_id = target_player_id)
  );
$$;

