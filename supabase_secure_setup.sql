  on public.calendar_events for all to authenticated
  using ((select public.is_staff()))
  with check ((select public.is_staff()));

-- INJURIES: Staff lo gestiona; familias solo ven las de su jugador
drop policy if exists "Staff manage injuries"    on public.injuries;
drop policy if exists "Families view own injuries" on public.injuries;
