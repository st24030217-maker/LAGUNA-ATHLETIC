-- JUSTIFICATIONS: Staff gestiona; familias ven y crean las suyas
drop policy if exists "Staff manage justifications"       on public.justifications;
drop policy if exists "Families view own justifications"  on public.justifications;
drop policy if exists "Families create own justifications" on public.justifications;
