-- 4.1 Auto-actualiza updated_at en cada UPDATE
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- 4.2 Crea perfil automáticamente cuando un usuario se registra en Auth
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', new.email))
  on conflict (id) do nothing;
  return new;
end;
$$;

-- 4.3 Función auxiliar: ¿es el usuario actual staff (admin/director/coach)?
create or replace function public.is_staff()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid())
      and role in ('admin', 'director', 'coach')
  );
$$;

-- 4.4 Función auxiliar: ¿tiene el usuario relación con el jugador indicado?
--     (como jugador mismo o como tutor/guardian)
create or replace function public.is_related_to_player(target_player_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    left join public.guardian_players gp on gp.guardian_id = p.id
    where p.id = (select auth.uid())
      and (p.player_id = target_player_id or gp.player_id = target_player_id)
  );
$$;

