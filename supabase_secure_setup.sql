  on public.payments for all to authenticated
  using ((select public.is_staff()))
  with check ((select public.is_staff()));
create policy "Families view their payments"
  on public.payments for select to authenticated
  using ((select public.is_related_to_player(player_id)));

-- CALENDAR EVENTS: Todos los autenticados ven el calendario; solo Staff edita
drop policy if exists "Authenticated users view calendar" on public.calendar_events;
drop policy if exists "Staff manage calendar"             on public.calendar_events;
