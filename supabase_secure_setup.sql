-- ── NUEVAS POLÍTICAS SEGURAS ─────────────────────────────────────────────────

-- PLAYERS: Staff lo gestiona todo; jugador/tutor solo ve su registro
drop policy if exists "Staff manage players"         on public.players;
drop policy if exists "Users view their player record" on public.players;
create policy "Staff manage players"
  on public.players for all to authenticated
  using ((select public.is_staff()))
  with check ((select public.is_staff()));
create policy "Users view their player record"
  on public.players for select to authenticated
  using ((select public.is_related_to_player(id)));

-- PROFILES: Cada usuario ve el suyo; Staff los gestiona todos
drop policy if exists "Users read own profile"  on public.profiles;
drop policy if exists "Staff manage profiles"   on public.profiles;
create policy "Users read own profile"
  on public.profiles for select to authenticated
  using (id = (select auth.uid()) or (select public.is_staff()));
create policy "Staff manage profiles"
  on public.profiles for all to authenticated
  using ((select public.is_staff()))
  with check ((select public.is_staff()));

-- GUARDIAN_PLAYERS: Tutor ve sus enlaces; Staff los gestiona
drop policy if exists "Guardians read their player links" on public.guardian_players;
drop policy if exists "Staff manage guardian links"       on public.guardian_players;
create policy "Guardians read their player links"
  on public.guardian_players for select to authenticated
  using (guardian_id = (select auth.uid()) or (select public.is_staff()));
create policy "Staff manage guardian links"
  on public.guardian_players for all to authenticated
  using ((select public.is_staff()))
  with check ((select public.is_staff()));

-- PAYMENTS: Staff lo gestiona; familias solo ven sus propios pagos
