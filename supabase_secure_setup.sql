-- 3. Privilegios y Row Level Security --------------------------------------

revoke all on all tables in schema public from anon;
revoke all on all sequences in schema public from anon;
revoke all on function public.is_staff() from public;
revoke all on function public.is_related_to_player(bigint) from public;

grant usage on schema public to authenticated;
grant select, insert, update, delete on table
  public.players, public.profiles, public.guardian_players, public.payments,
  public.calendar_events, public.injuries, public.attendance_logs,
  public.justifications to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on function public.is_staff() to authenticated;
grant execute on function public.is_related_to_player(bigint) to authenticated;

alter table public.players enable row level security;
alter table public.profiles enable row level security;
alter table public.guardian_players enable row level security;
alter table public.payments enable row level security;
alter table public.calendar_events enable row level security;
alter table public.injuries enable row level security;
alter table public.attendance_logs enable row level security;
alter table public.justifications enable row level security;

drop policy if exists "Staff manage players" on public.players;
drop policy if exists "Users view their player record" on public.players;
create policy "Staff manage players" on public.players for all to authenticated
  using ((select public.is_staff())) with check ((select public.is_staff()));
create policy "Users view their player record" on public.players for select to authenticated
  using ((select public.is_related_to_player(id)));

