create table if not exists public.players (
  id bigint generated by default as identity primary key,
  number integer not null unique,
  name text not null,
  position text not null,
  position_alt text,
  player_group text not null default 'Sin Cat.',
  status text not null default 'Ausente',
  checkin_time text not null default '-',
  attendance_pct numeric(5,2) not null default 0 check (attendance_pct between 0 and 100),
  streak text not null default '0 A',
  starter boolean not null default false,
  injured boolean not null default false,
  goals integer not null default 0 check (goals >= 0),
  assists integer not null default 0 check (assists >= 0),
  mins integer not null default 0 check (mins >= 0),
  cards integer not null default 0 check (cards >= 0),
  reg_status text not null default 'Activo',
  birthdate date,
  tutor_name text,
  phone text,
  photo text not null default 'LAGUNA.jpg',
  contacts jsonb not null default '[]'::jsonb,
  doc_acta boolean not null default false,
  doc_curp boolean not null default false,
  doc_medico boolean not null default false,
  doc_ine boolean not null default false,
  doc_escolar boolean not null default false,
  game_info jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
