-- ATTENDANCE_LOGS: Staff lo gestiona; familias solo ven la asistencia de su jugador
drop policy if exists "Staff manage attendance"       on public.attendance_logs;
drop policy if exists "Families view own attendance"  on public.attendance_logs;
create policy "Staff manage attendance"
